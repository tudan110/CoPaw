#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
参数正常范围表（数据来源：《城域网核心路由器光模块老化故障根因定位方案》）

这个文件只做一件事：把文档里"第三步：指标验证"章节给出的那张表格，
翻译成 Python 里可以直接比较的数字。它不连接任何设备、不发任何网络
请求，纯粹是"常识表格"的代码化，方便主脚本 diagnose_optical_aging.py
调用。

如果你想把这个示例改造成自己的场景，只需要把下面这些数值换成你自己
业务的正常范围表即可，其余脚本逻辑基本不用动。
"""

from typing import Tuple


# ------------------------------------------------------------------
# 接收光功率（单位：dBm）
# ------------------------------------------------------------------
# 文档里给的正常范围是 -19 ~ -5 dBm。
# 文档里同时提到"典型接收灵敏度下限是 -22 dBm"——意思是，只要接收光
# 功率低于这个值，说明信号已经弱到设备快"看不清"了，这是最直接的
# "光模块可能老化/衰减过大"的信号。
RX_POWER_NORMAL_RANGE: Tuple[float, float] = (-19.0, -5.0)
RX_POWER_SENSITIVITY_LIMIT: float = -22.0

# ------------------------------------------------------------------
# 发送光功率（单位：dBm）
# ------------------------------------------------------------------
# 正常范围 -5 ~ 0 dBm。文档的故障案例里发送光功率是正常的（说明发射
# 端没问题，问题出在接收端），所以这一项主要用来"排除法"：
# 如果发送光功率也异常，说明本端光模块的发射器件可能也有问题，而不
# 只是简单的"接收端老化"。
TX_POWER_NORMAL_RANGE: Tuple[float, float] = (-5.0, 0.0)

# ------------------------------------------------------------------
# 偏置电流（单位：mA）
# ------------------------------------------------------------------
# 正常范围 5 ~ 50 mA。激光器随着使用时间增长会逐渐老化、发光效率下降，
# 为了维持同样的发送光功率，驱动电路会不断加大偏置电流去"硬撑"，所以
# 偏置电流持续偏高，是光模块老化最典型的早期信号之一。
BIAS_CURRENT_NORMAL_RANGE: Tuple[float, float] = (5.0, 50.0)

# ------------------------------------------------------------------
# 温度（单位：°C）
# ------------------------------------------------------------------
# 正常范围 0 ~ 70°C，超过 70°C 会加速器件老化。
# 文档"预防措施"里额外建议"温度超过 65°C 自动告警"——也就是在真正
# 超过 70°C 上限之前，提前 5°C 留出预警空间，方便运维提前介入。
TEMPERATURE_NORMAL_RANGE: Tuple[float, float] = (0.0, 70.0)
TEMPERATURE_WARNING_THRESHOLD: float = 65.0

# ------------------------------------------------------------------
# CRC 错误计数增长速率（单位：个/秒）
# ------------------------------------------------------------------
# 正常情况下应该是 0（不增长）。文档没有给出一个具体的"故障阈值"，
# 只要求关注"是否持续增长"，所以这里只要大于 0 就视为异常。
CRC_RATE_NORMAL: float = 0.0

# ------------------------------------------------------------------
# 拓扑-时序传播延迟经验值（单位：分钟）
# ------------------------------------------------------------------
# 文档"第二步：拓扑-时序双约束因果链推理"提到：核心层设备出问题后，
# 下游（汇聚层）设备的告警时间通常会晚 1~2 分钟才出现。如果下游告警
# 比这个端口的告警还早，或者晚了特别久（比如超过 10 分钟），说明两者
# 之间的因果关系存疑，需要人工复核，不能简单套用这套四步法结论。
TOPOLOGY_PROPAGATION_DELAY_RANGE_MIN: Tuple[float, float] = (1.0, 2.0)
# 超过这个上限，就认为"时间上对不上"，需要人工复核而不是自动下结论
TOPOLOGY_PROPAGATION_DELAY_TOLERANCE_MIN: float = 10.0


def is_out_of_range(value: float, normal_range: Tuple[float, float]) -> bool:
    """
    最基础的工具函数：判断 value 是否落在 [下限, 上限] 之外。

    这里特意单独抽出来，是因为"是否在正常范围内"这个判断在脚本里会
    被反复用到（光功率、偏置电流、温度都要这么判断一次），抽成一个
    函数可以避免每处都重复写 `value < low or value > high` 这种代码，
    也方便以后只改一个地方。
    """
    low, high = normal_range
    return value < low or value > high
